import { useState } from "react";
import { Link } from "react-router-dom";
import { Sparkles } from "lucide-react";
import { PageHeader } from "@/components/layout/PageHeader";
import { ListSkeleton } from "@/components/common/Skeleton";
import { ErrorState } from "@/components/common/ErrorState";
import { EmptyState } from "@/components/common/EmptyState";
import { Button } from "@/components/common/Button";
import { RecommendationCard } from "@/components/problems/RecommendationCard";
import { useRecommendations } from "@/lib/api/queries";
import { cn } from "@/utils/cn";

const tabs = [
  { key: "pending", label: "Pending" },
  { key: "completed", label: "Completed" },
  { key: "all", label: "All" },
] as const;

export default function RecommendationsPage() {
  const [tab, setTab] = useState<(typeof tabs)[number]["key"]>("pending");
  const recs = useRecommendations();

  const items = (recs.data ?? []).filter((r) => (tab === "all" ? true : r.status === tab));

  return (
    <div>
      <PageHeader
        title="Recommendations"
        description="Personalized problems generated by the Path Pointer engine from your mastery scores, weak topics and recent activity."
        action={
          <Button variant="secondary" size="sm" onClick={() => void recs.refetch()} loading={recs.isFetching}>
            Refresh
          </Button>
        }
      />

      <div className="mb-4 inline-flex rounded-lg border border-white/[0.08] bg-white/[0.02] p-1">
        {tabs.map((t) => (
          <button
            key={t.key}
            onClick={() => setTab(t.key)}
            aria-pressed={tab === t.key}
            className={cn(
              "rounded-md px-3 py-1.5 text-[12.5px] font-medium transition-colors",
              tab === t.key ? "bg-white/[0.08] text-white" : "text-slate-400 hover:text-slate-200",
            )}
          >
            {t.label}
          </button>
        ))}
      </div>

      {recs.isLoading ? (
        <ListSkeleton rows={4} />
      ) : recs.isError ? (
        <ErrorState
          title="We couldn't load your recommendations"
          description="The recommendations API didn't respond."
          onRetry={() => void recs.refetch()}
          retrying={recs.isFetching}
        />
      ) : items.length === 0 ? (
        <EmptyState
          icon={<Sparkles className="size-5" aria-hidden />}
          title={tab === "completed" ? "Nothing completed yet" : "No recommendations yet"}
          description={
            tab === "completed"
              ? "Recommendations you finish will be listed here."
              : "The engine generates new problems as your mastery data updates. Solve a few problems to prime it."
          }
          action={
            <Link to="/dashboard/problems">
              <Button size="sm" variant="secondary">
                Browse the problem library
              </Button>
            </Link>
          }
        />
      ) : (
        <div className="space-y-3">
          {items.map((rec, i) => (
            <RecommendationCard key={rec.id} rec={rec} index={i} />
          ))}
        </div>
      )}
    </div>
  );
}
